pierwsza_wartosc = bool(int(input("Podaj pierwszą wartość, 1 dla True lub 0 dla False: ")))

druga_wartosc = bool(int(input("Podaj drugą wartość, 1 dla True lub 0 dla False: ")))

print(f"AND: {pierwsza_wartosc and druga_wartosc}")
print(f"OR: {pierwsza_wartosc or druga_wartosc}") 

