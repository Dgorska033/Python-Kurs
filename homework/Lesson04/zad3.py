# Zadanie 3 - Porównanie is vs ==

lista1 = [1 , 1] 
lista2 = [1 , 1] 

print(f"Czy lista1 i lista2 to ten sam obiekt? {lista1 is lista2}") 
print(f"CZy lista1 i lista2 jest taka sama? {lista1 == lista2}") 

# lista1 i lista2 to nie ten sam obiekt, dla Pythona = False, bo to są dwie rózne zmienne
# lista1 i lista2 w porównaniu to True, ponieważ Python porównuje wartości listy

